"""Collect every figure used in the response letter into one folder as vector PDF, numbered as in the letter.
Output: manuscript/Figures_Response/Figure01_<name>.pdf ... plus a README listing figure number, file and caption."""
import re, shutil
from pathlib import Path
MS = Path(__file__).resolve().parents[2] / "manuscript"; OUT = MS / "Figures_Response"; OUT.mkdir(exist_ok=True)
md = (MS / "PEARL_Response_to_Reviewers.md").read_text()
rows = []
for n, cap, rel in re.findall(r"!\[\*\*Figure (\d+)\.\*\*(.*?)\]\((\.\./[^)]+)\)", md, flags=re.S):
    src = (MS / rel).resolve(); assert src.exists() and src.suffix == ".pdf", src
    dst = OUT / f"Figure{int(n):02d}_{src.stem}.pdf"; shutil.copy2(src, dst)
    rows.append((int(n), dst.name, " ".join(cap.split()), rel))
rows.sort()
(OUT / "README.md").write_text("# Figures of the response to reviewers\n\nVector PDF, one file per figure, numbered as in `PEARL_Response_to_Reviewers.md`.\nGenerated by `scripts/revision/collect_response_figures.py`; the source of each file is listed below.\n\n" +
    "\n".join(f"- **Figure {n}** `{f}` - {c}\n  (source: `{s.replace('../','')}`)" for n, f, c, s in rows) + "\n")
print(f"{len(rows)} figures copied to {OUT}")
for n, f, c, s in rows: print(f"  Figure {n:2d}  {f}")
